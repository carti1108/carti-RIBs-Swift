public enum AndroidBridgeGenerator {
    public static func generateHandle(for spec: FeatureBridgeSpec) -> String {
        let feature = spec.featureName
        var lines: [String] = []
        lines.append("// Generated by bridge-gen. Do not edit manually.")
        lines.append("import Feature\(feature)Android")
        lines.append("")

        // 1. Boundary value structs for external struct array fields (ADR-0023)
        let arrayFields = spec.stateFields.compactMap { field -> (field: ValueField, structSpec: ValueStructSpec)? in
            guard case .array(.customStruct(let structName)) = field.type,
                  let structSpec = spec.referencedStructs[structName] else {
                return nil
            }
            return (field, structSpec)
        }

        var emittedStructNames: Set<String> = []
        for entry in arrayFields {
            let boundaryName = "\(feature)\(entry.structSpec.name)"
            guard emittedStructNames.insert(boundaryName).inserted else { continue }
            lines.append("public struct \(boundaryName): Sendable {")
            for field in entry.structSpec.fields {
                lines.append("    public let \(field.name): \(androidTypeName(field.type, feature: feature))")
            }
            lines.append("")
            let initParams = entry.structSpec.fields
                .map { "\($0.name): \(androidTypeName($0.type, feature: feature))" }
                .joined(separator: ", ")
            lines.append("    public init(\(initParams)) {")
            for field in entry.structSpec.fields {
                lines.append("        self.\(field.name) = \(field.name)")
            }
            lines.append("    }")
            lines.append("}")
            lines.append("")
        }

        // 2. ViewBridge protocol
        let directFields = spec.stateFields.filter { field in
            if case .array(.customStruct) = field.type { return false }
            return true
        }

        lines.append("public protocol \(feature)ViewBridge {")
        if !directFields.isEmpty {
            let renderParams = directFields
                .map { "\($0.name): \(androidTypeName($0.type, feature: feature))" }
                .joined(separator: ", ")
            lines.append("    func render(\(renderParams))")
        }
        for entry in arrayFields {
            lines.append("    func \(entry.field.name)Changed()")
        }
        lines.append("}")
        lines.append("")

        // 3. ScreenHandle class
        lines.append("public final class \(feature)ScreenHandle: Sendable {")
        lines.append("    private let screenID: Int64")
        lines.append("")
        lines.append("    public init(screenID: Int64) {")
        lines.append("        self.screenID = screenID")
        lines.append("    }")
        lines.append("")
        lines.append("    public func attach(view: any \(feature)ViewBridge) {")
        lines.append("        nonisolated(unsafe) let view = view")
        lines.append("        MainActor.assumeIsolated {")
        lines.append("            screen?.attach { state in")
        if !directFields.isEmpty {
            let renderArgs = directFields
                .map { "\($0.name): state.\($0.name)" }
                .joined(separator: ", ")
            lines.append("                view.render(\(renderArgs))")
        }
        for entry in arrayFields {
            lines.append("                view.\(entry.field.name)Changed()")
        }
        lines.append("            }")
        lines.append("        }")
        lines.append("    }")
        lines.append("")
        lines.append("    public func detach() {")
        lines.append("        MainActor.assumeIsolated { screen?.detach() }")
        lines.append("    }")

        // Pull getters for custom struct arrays
        for entry in arrayFields {
            let boundaryName = "\(feature)\(entry.structSpec.name)"
            let mapArgs = entry.structSpec.fields
                .map { "\($0.name): $0.\($0.name)" }
                .joined(separator: ", ")
            lines.append("")
            lines.append("    public func \(entry.field.name)() -> [\(boundaryName)] {")
            lines.append("        MainActor.assumeIsolated {")
            lines.append("            (screen?.currentState.\(entry.field.name) ?? []).map { \(boundaryName)(\(mapArgs)) }")
            lines.append("        }")
            lines.append("    }")
        }

        // Action methods
        for action in spec.actions {
            let paramsDecl = action.params.map { param in
                let typeStr = androidTypeName(param.type, feature: feature)
                if let label = param.label {
                    return label == param.name ? "\(param.name): \(typeStr)" : "\(label) \(param.name): \(typeStr)"
                } else {
                    return "_ \(param.name): \(typeStr)"
                }
            }.joined(separator: ", ")

            let callArgs = action.params.map { param in
                if let label = param.label {
                    return "\(label): \(param.name)"
                } else {
                    return param.name
                }
            }.joined(separator: ", ")

            let actionExpr = callArgs.isEmpty ? ".\(action.name)" : ".\(action.name)(\(callArgs))"
            lines.append("")
            lines.append("    public func \(action.name)(\(paramsDecl)) {")
            lines.append("        MainActor.assumeIsolated { screen?.send(\(actionExpr)) }")
            lines.append("    }")
        }

        lines.append("")
        lines.append("    @MainActor private var screen: \(feature)AndroidScreen? {")
        lines.append("        controller?.screen(id: screenID, as: \(feature)AndroidScreen.self)")
        lines.append("    }")
        lines.append("}")
        lines.append("")

        return lines.joined(separator: "\n")
    }

    private static func androidTypeName(_ type: BridgeType, feature: String) -> String {
        switch type {
        case .primitive(let p): return p.rawValue
        case .optional(let inner): return "\(androidTypeName(inner, feature: feature))?"
        case .array(let inner): return "[\(androidTypeName(inner, feature: feature))]"
        case .customStruct(let name): return "\(feature)\(name)"
        }
    }
}
