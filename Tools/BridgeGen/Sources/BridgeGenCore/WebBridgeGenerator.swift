public enum WebBridgeGenerator {
    public static func generateBridge(for spec: FeatureBridgeSpec) -> String {
        let feature = spec.featureName
        var lines: [String] = []
        lines.append("// Generated by bridge-gen. Do not edit manually.")
        lines.append("import JavaScriptKit")
        lines.append("")

        // 1. @JS boundary value structs
        var emittedStructs: Set<String> = []
        for field in spec.stateFields {
            if case .array(.customStruct(let structName)) = field.type,
               let structSpec = spec.referencedStructs[structName] {
                let boundaryName = "\(feature)\(structSpec.name)"
                guard emittedStructs.insert(boundaryName).inserted else { continue }
                lines.append("@JS struct \(boundaryName) {")
                for subField in structSpec.fields {
                    lines.append("    let \(subField.name): \(webTypeName(subField.type, feature: feature))")
                }
                lines.append("}")
                lines.append("")
            }
        }

        // 2. @JS protocol <Name>ViewBridge
        lines.append("@JS protocol \(feature)ViewBridge {")
        if spec.hasChildSlots {
            lines.append("    func mount(host: JSObject, content: JSObject, handle: \(feature)ScreenHandle)")
        } else {
            lines.append("    func mount(host: JSObject, handle: \(feature)ScreenHandle)")
        }
        if !spec.stateFields.isEmpty {
            let renderParams = spec.stateFields
                .map { "\($0.name): \(webTypeName($0.type, feature: feature))" }
                .joined(separator: ", ")
            lines.append("    func render(\(renderParams))")
        }
        lines.append("}")
        lines.append("")

        // 3. @JS final class <Name>ScreenHandle
        lines.append("@JS final class \(feature)ScreenHandle: Sendable {")
        for action in spec.actions {
            let closureParams = action.params
                .map { webTypeName($0.type, feature: feature) }
                .joined(separator: ", ")
            lines.append("    private let on\(capitalized(action.name)): @MainActor @Sendable (\(closureParams)) -> Void")
        }
        lines.append("")
        if spec.actions.isEmpty {
            lines.append("    init() {}")
        } else {
            lines.append("    init(")
            for (idx, action) in spec.actions.enumerated() {
                let closureParams = action.params
                    .map { webTypeName($0.type, feature: feature) }
                    .joined(separator: ", ")
                let comma = idx < spec.actions.count - 1 ? "," : ""
                lines.append("        on\(capitalized(action.name)): @escaping @MainActor @Sendable (\(closureParams)) -> Void\(comma)")
            }
            lines.append("    ) {")
            for action in spec.actions {
                let prop = "on\(capitalized(action.name))"
                lines.append("        self.\(prop) = \(prop)")
            }
            lines.append("    }")
        }

        for action in spec.actions {
            let paramsDecl = action.params.map { param in
                let typeStr = webTypeName(param.type, feature: feature)
                if let label = param.label {
                    return label == param.name ? "\(param.name): \(typeStr)" : "\(label) \(param.name): \(typeStr)"
                } else {
                    return "_ \(param.name): \(typeStr)"
                }
            }.joined(separator: ", ")
            let callArgs = action.params.map(\.name).joined(separator: ", ")
            lines.append("")
            lines.append("    @JS func \(action.name)(\(paramsDecl)) {")
            lines.append("        MainActor.assumeIsolated { on\(capitalized(action.name))(\(callArgs)) }")
            lines.append("    }")
        }

        lines.append("}")
        lines.append("")
        return lines.joined(separator: "\n")
    }

    public static func generateViewMounts(for specs: [FeatureBridgeSpec]) -> String {
        var lines: [String] = []
        lines.append("// Generated by bridge-gen. Do not edit manually.")
        for spec in specs.sorted(by: { $0.featureName < $1.featureName }) {
            lines.append("import Feature\(spec.featureName)Web")
        }
        lines.append("import TodoWebSupport")
        lines.append("")
        lines.append("@MainActor")
        lines.append("enum ViewMounts {")

        for (index, spec) in specs.enumerated() {
            let feature = spec.featureName
            let methodName = lowercasedFirst(feature)
            lines.append("    static func \(methodName)(_ view: any \(feature)ViewBridge) -> \(feature)WebViewFactory {")
            lines.append("        \(feature)WebViewFactory { screen in")

            if spec.actions.isEmpty {
                lines.append("            let handle = \(feature)ScreenHandle()")
            } else {
                lines.append("            let handle = \(feature)ScreenHandle(")
                for (aIdx, action) in spec.actions.enumerated() {
                    let comma = aIdx < spec.actions.count - 1 ? "," : ""
                    let paramNames = action.params.map(\.name).joined(separator: ", ")
                    let closureSig = paramNames.isEmpty ? "[weak screen] in" : "[weak screen] \(paramNames) in"
                    let sendArgs = action.params.map { param in
                        let converted = convertFromWeb(expr: param.name, to: param.type)
                        if let label = param.label {
                            return "\(label): \(converted)"
                        } else {
                            return converted
                        }
                    }.joined(separator: ", ")
                    let actionExpr = sendArgs.isEmpty ? ".\(action.name)" : ".\(action.name)(\(sendArgs))"
                    lines.append("                on\(capitalized(action.name)): { \(closureSig) screen?.send(\(actionExpr)) }\(comma)")
                }
                lines.append("            )")
            }

            if spec.hasChildSlots {
                lines.append("            view.mount(host: screen.element, content: screen.content, handle: handle)")
            } else {
                lines.append("            view.mount(host: screen.element, handle: handle)")
            }

            if !spec.stateFields.isEmpty {
                lines.append("            screen.attach { state in")
                let renderArgs = spec.stateFields.map { field in
                    let expr = convertToWeb(
                        expr: "state.\(field.name)",
                        type: field.type,
                        feature: feature,
                        structs: spec.referencedStructs
                    )
                    return "\(field.name): \(expr)"
                }.joined(separator: ", ")
                lines.append("                view.render(\(renderArgs))")
                lines.append("            }")
            }

            lines.append("        }")
            lines.append("    }")
            if index < specs.count - 1 {
                lines.append("")
            }
        }

        lines.append("}")
        lines.append("")
        return lines.joined(separator: "\n")
    }

    private static func webTypeName(_ type: BridgeType, feature: String) -> String {
        switch type {
        case .primitive(.int64): return "Int"
        case .primitive(let p): return p.rawValue
        case .optional(let inner): return "\(webTypeName(inner, feature: feature))?"
        case .array(let inner): return "[\(webTypeName(inner, feature: feature))]"
        case .customStruct(let name): return "\(feature)\(name)"
        }
    }

    private static func convertToWeb(
        expr: String,
        type: BridgeType,
        feature: String,
        structs: [String: ValueStructSpec]
    ) -> String {
        switch type {
        case .primitive(.int64):
            return "Int(\(expr))"
        case .primitive:
            return expr
        case .optional(.primitive(.int64)):
            return "\(expr).map(Int.init)"
        case .optional:
            return expr
        case .array(.customStruct(let structName)):
            guard let structSpec = structs[structName] else { return expr }
            let boundaryName = "\(feature)\(structSpec.name)"
            let fields = structSpec.fields.map { f in
                let innerExpr = convertToWeb(expr: "$0.\(f.name)", type: f.type, feature: feature, structs: structs)
                return "\(f.name): \(innerExpr)"
            }.joined(separator: ", ")
            return "\(expr).map { \(boundaryName)(\(fields)) }"
        case .array(.primitive(.int64)):
            return "\(expr).map(Int.init)"
        case .array:
            return expr
        case .customStruct:
            return expr
        }
    }

    private static func convertFromWeb(expr: String, to type: BridgeType) -> String {
        switch type {
        case .primitive(.int64):
            return "Int64(\(expr))"
        case .optional(.primitive(.int64)):
            return "\(expr).map(Int64.init)"
        default:
            return expr
        }
    }

    private static func capitalized(_ text: String) -> String {
        guard let first = text.first else { return text }
        return first.uppercased() + text.dropFirst()
    }

    private static func lowercasedFirst(_ text: String) -> String {
        guard let first = text.first else { return text }
        return first.lowercased() + text.dropFirst()
    }
}
