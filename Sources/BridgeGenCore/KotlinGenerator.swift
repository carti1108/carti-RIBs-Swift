public enum KotlinGenerator {
    public static func generate(schema: BridgeSchema, packageName: String) -> String {
        var lines: [String] = []
        lines.append("// Generated by bridge-gen. Do not edit manually.")
        lines.append("package \(packageName)")
        lines.append("")
        lines.append("import org.json.JSONArray")
        lines.append("import org.json.JSONObject")
        lines.append("")

        for fullName in schema.orderedTypeNames {
            guard let spec = schema.namedTypes[fullName] else { continue }
            let ktName = ktTypeName(for: fullName)
            switch spec {
            case .enum(let e):
                if e.isSimple {
                    emitSimpleEnum(name: ktName, cases: e.cases, into: &lines)
                } else {
                    emitSealedEnum(name: ktName, cases: e.cases, schema: schema, into: &lines)
                }
            case .struct(let s):
                emitDataClass(name: ktName, fields: s.fields, schema: schema, into: &lines)
            }
            lines.append("")
        }

        for feature in schema.features {
            emitDataClass(name: feature.stateTypeName, fields: feature.stateFields, schema: schema, into: &lines)
            lines.append("")
            emitSealedEnum(name: feature.actionTypeName, cases: feature.actions, schema: schema, into: &lines)
            lines.append("")
        }

        return lines.joined(separator: "\n")
    }

    private static func emitSimpleEnum(name: String, cases: [EnumCaseSpec], into lines: inout [String]) {
        lines.append("enum class \(name)(val rawValue: String) {")
        for (idx, c) in cases.enumerated() {
            let sep = idx < cases.count - 1 ? "," : ";"
            lines.append("    \(pascalCase(c.name))(\"\(c.name)\")\(sep)")
        }
        lines.append("")
        lines.append("    companion object {")
        lines.append("        fun fromJsonValue(raw: String): \(name) =")
        lines.append("            entries.firstOrNull { it.rawValue == raw }")
        lines.append("                ?: error(\"Unknown \(name): $raw\")")
        lines.append("    }")
        lines.append("}")
    }

    private static func emitDataClass(name: String, fields: [ValueField], schema: BridgeSchema, into lines: inout [String]) {
        lines.append("data class \(name)(")
        for (idx, field) in fields.enumerated() {
            let comma = idx < fields.count - 1 ? "," : ""
            lines.append("    val \(field.name): \(ktType(field.type))\(comma)")
        }
        lines.append(") {")
        lines.append("    companion object {")
        lines.append("        fun fromJson(json: JSONObject): \(name) = \(name)(")
        for (idx, field) in fields.enumerated() {
            let comma = idx < fields.count - 1 ? "," : ""
            let expr = ktDecodeField(field.name, type: field.type, schema: schema)
            lines.append("            \(field.name) = \(expr)\(comma)")
        }
        lines.append("        )")
        lines.append("    }")
        lines.append("}")
    }

    private static func emitSealedEnum(name: String, cases: [EnumCaseSpec], schema: BridgeSchema, into lines: inout [String]) {
        lines.append("sealed interface \(name) {")
        lines.append("    fun toJson(): JSONObject")
        lines.append("")
        for c in cases {
            let caseName = pascalCase(c.name)
            if c.params.isEmpty {
                lines.append("    data object \(caseName) : \(name) {")
                lines.append("        override fun toJson(): JSONObject = JSONObject().put(\"kind\", \"\(c.name)\")")
                lines.append("    }")
            } else {
                lines.append("    data class \(caseName)(")
                for (idx, p) in c.params.enumerated() {
                    let comma = idx < c.params.count - 1 ? "," : ""
                    lines.append("        val \(p.name): \(ktType(p.type))\(comma)")
                }
                lines.append("    ) : \(name) {")
                lines.append("        override fun toJson(): JSONObject = JSONObject().apply {")
                lines.append("            put(\"kind\", \"\(c.name)\")")
                for p in c.params {
                    lines.append("            put(\"\(p.name)\", \(ktEncodeExpr(p.name, type: p.type, schema: schema)))")
                }
                lines.append("        }")
                lines.append("    }")
            }
        }
        lines.append("")
        lines.append("    companion object {")
        lines.append("        fun fromJson(json: JSONObject): \(name) = when (val kind = json.getString(\"kind\")) {")
        for c in cases {
            let caseName = pascalCase(c.name)
            if c.params.isEmpty {
                lines.append("            \"\(c.name)\" -> \(caseName)")
            } else {
                let args = c.params
                    .map { "\($0.name) = \(ktDecodeField($0.name, type: $0.type, schema: schema))" }
                    .joined(separator: ", ")
                lines.append("            \"\(c.name)\" -> \(caseName)(\(args))")
            }
        }
        lines.append("            else -> error(\"Unknown \(name) kind: $kind\")")
        lines.append("        }")
        lines.append("    }")
        lines.append("}")
    }

    private static func ktDecodeField(_ key: String, type: BridgeType, schema: BridgeSchema) -> String {
        switch type {
        case .primitive(.bool): return "json.getBoolean(\"\(key)\")"
        case .primitive(.int): return "json.getInt(\"\(key)\")"
        case .primitive(.int64): return "json.getLong(\"\(key)\")"
        case .primitive(.double): return "json.getDouble(\"\(key)\")"
        case .primitive(.string): return "json.getString(\"\(key)\")"
        case .optional(let inner):
            let nonNull = ktDecodeField(key, type: inner, schema: schema)
            return "if (json.isNull(\"\(key)\")) null else \(nonNull)"
        case .array(let element):
            let itemExpr = ktDecodeArrayElement(element, schema: schema)
            return "json.getJSONArray(\"\(key)\").let { arr -> List(arr.length()) { i -> \(itemExpr) } }"
        case .named(let fullName):
            let ktName = ktTypeName(for: fullName)
            if case .enum(let e) = schema.namedTypes[fullName], e.isSimple {
                return "\(ktName).fromJsonValue(json.getString(\"\(key)\"))"
            }
            return "\(ktName).fromJson(json.getJSONObject(\"\(key)\"))"
        }
    }

    private static func ktDecodeArrayElement(_ type: BridgeType, schema: BridgeSchema) -> String {
        switch type {
        case .primitive(.bool): return "arr.getBoolean(i)"
        case .primitive(.int): return "arr.getInt(i)"
        case .primitive(.int64): return "arr.getLong(i)"
        case .primitive(.double): return "arr.getDouble(i)"
        case .primitive(.string): return "arr.getString(i)"
        case .named(let fullName):
            let ktName = ktTypeName(for: fullName)
            if case .enum(let e) = schema.namedTypes[fullName], e.isSimple {
                return "\(ktName).fromJsonValue(arr.getString(i))"
            }
            return "\(ktName).fromJson(arr.getJSONObject(i))"
        case .optional(let inner):
            return "if (arr.isNull(i)) null else \(ktDecodeArrayElement(inner, schema: schema))"
        case .array:
            return "arr.get(i)"
        }
    }

    private static func ktEncodeExpr(_ expr: String, type: BridgeType, schema: BridgeSchema) -> String {
        switch type {
        case .primitive:
            return expr
        case .optional(let inner):
            if case .primitive = inner {
                return "\(expr) ?: JSONObject.NULL"
            }
            return "\(expr)?.let { \(ktEncodeExpr("it", type: inner, schema: schema)) } ?: JSONObject.NULL"
        case .array(let inner):
            let mapItem = ktEncodeExpr("it", type: inner, schema: schema)
            return "JSONArray().apply { \(expr).forEach { put(\(mapItem)) } }"
        case .named(let fullName):
            if case .enum(let e) = schema.namedTypes[fullName], e.isSimple {
                return "\(expr).rawValue"
            }
            return "\(expr).toJson()"
        }
    }

    private static func ktType(_ type: BridgeType) -> String {
        switch type {
        case .primitive(.bool): return "Boolean"
        case .primitive(.int): return "Int"
        case .primitive(.int64): return "Long"
        case .primitive(.double): return "Double"
        case .primitive(.string): return "String"
        case .optional(let inner): return "\(ktType(inner))?"
        case .array(let inner): return "List<\(ktType(inner))>"
        case .named(let fullName): return ktTypeName(for: fullName)
        }
    }

    private static func ktTypeName(for fullName: String) -> String {
        fullName.split(separator: ".").map(String.init).joined()
    }

    private static func pascalCase(_ name: String) -> String {
        guard let first = name.first else { return name }
        return first.uppercased() + name.dropFirst()
    }
}
