public enum TypeScriptGenerator {
    public static func generate(schema: BridgeSchema) -> String {
        var lines: [String] = []
        lines.append("// Generated by bridge-gen. Do not edit manually.")
        lines.append("")

        for fullName in schema.orderedTypeNames {
            guard let spec = schema.namedTypes[fullName] else { continue }
            let tsName = tsTypeName(for: fullName)
            switch spec {
            case .enum(let e):
                if e.isSimple {
                    let cases = e.cases.map { "\"\($0.name)\"" }.joined(separator: " | ")
                    lines.append("export type \(tsName) = \(cases);")
                } else {
                    lines.append("export type \(tsName) =")
                    for c in e.cases {
                        lines.append("  | \(tsCaseUnion(c, schema: schema))")
                    }
                    lines[lines.count - 1] += ";"
                }
            case .struct(let s):
                lines.append("export type \(tsName) = {")
                for field in s.fields {
                    lines.append("  \(field.name): \(tsType(field.type, schema: schema));")
                }
                lines.append("};")
            }
            lines.append("")
        }

        for feature in schema.features {
            lines.append("export type \(feature.stateTypeName) = {")
            for field in feature.stateFields {
                lines.append("  \(field.name): \(tsType(field.type, schema: schema));")
            }
            lines.append("};")
            lines.append("")

            lines.append("export type \(feature.actionTypeName) =")
            for action in feature.actions {
                lines.append("  | \(tsCaseUnion(action, schema: schema))")
            }
            lines[lines.count - 1] += ";"
            lines.append("")
        }

        return lines.joined(separator: "\n")
    }

    private static func tsCaseUnion(_ c: EnumCaseSpec, schema: BridgeSchema) -> String {
        if c.params.isEmpty {
            return "{ kind: \"\(c.name)\" }"
        }
        let fields = c.params
            .map { "\($0.name): \(tsType($0.type, schema: schema))" }
            .joined(separator: "; ")
        return "{ kind: \"\(c.name)\"; \(fields) }"
    }

    private static func tsType(_ type: BridgeType, schema: BridgeSchema) -> String {
        switch type {
        case .primitive(.bool): return "boolean"
        case .primitive(.int), .primitive(.int64), .primitive(.double): return "number"
        case .primitive(.string): return "string"
        case .optional(let inner): return "\(tsType(inner, schema: schema)) | null"
        case .array(let inner): return "\(tsType(inner, schema: schema))[]"
        case .named(let fullName): return tsTypeName(for: fullName)
        }
    }

    private static func tsTypeName(for fullName: String) -> String {
        fullName.split(separator: ".").map(String.init).joined()
    }
}
