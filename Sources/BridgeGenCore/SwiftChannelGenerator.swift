public enum SwiftChannelGenerator {
    public static func generate(schema: BridgeSchema) -> String {
        var lines: [String] = []
        lines.append("// Generated by bridge-gen. Do not edit manually.")
        for mod in schema.importedModules {
            lines.append("import \(mod)")
        }
        lines.append("")
        lines.append(runtimeJSONHelpers)
        lines.append("")

        for fullName in schema.orderedTypeNames {
            guard let spec = schema.namedTypes[fullName] else { continue }
            let fnSuffix = swiftFuncSuffix(for: fullName)
            switch spec {
            case .struct(let s):
                emitStructEncoder(fnName: "encode\(fnSuffix)", swiftType: fullName, fields: s.fields, schema: schema, into: &lines)
                lines.append("")
                emitStructDecoder(fnName: "decode\(fnSuffix)", swiftType: fullName, fields: s.fields, schema: schema, into: &lines)
                lines.append("")
            case .enum(let e):
                emitEnumEncoder(fnName: "encode\(fnSuffix)", swiftType: fullName, spec: e, schema: schema, into: &lines)
                lines.append("")
                emitEnumDecoder(fnName: "decode\(fnSuffix)", swiftType: fullName, spec: e, schema: schema, into: &lines)
                lines.append("")
            }
        }

        for feature in schema.features {
            emitStructEncoder(
                fnName: "encode\(feature.stateTypeName)",
                swiftType: feature.stateTypeName,
                fields: feature.stateFields,
                schema: schema,
                into: &lines
            )
            lines.append("")
            lines.append("func encode\(feature.stateTypeName)JSON(_ value: \(feature.stateTypeName)) -> String {")
            lines.append("    var writer = BridgeJSONWriter()")
            lines.append("    encode\(feature.stateTypeName)(value, into: &writer)")
            lines.append("    return writer.result")
            lines.append("}")
            lines.append("")

            emitEnumDecoder(
                fnName: "decode\(feature.actionTypeName)",
                swiftType: feature.actionTypeName,
                spec: EnumSpec(fullName: feature.actionTypeName, simpleName: feature.actionTypeName, cases: feature.actions),
                schema: schema,
                forceTaggedObject: true,
                into: &lines
            )
            lines.append("")
            lines.append("func decode\(feature.actionTypeName)JSON(_ json: String) throws -> \(feature.actionTypeName) {")
            lines.append("    let value = try BridgeJSONParser.parse(json)")
            lines.append("    return try decode\(feature.actionTypeName)(from: value)")
            lines.append("}")
            lines.append("")
        }

        return lines.joined(separator: "\n")
    }

    private static func emitStructEncoder(
        fnName: String,
        swiftType: String,
        fields: [ValueField],
        schema: BridgeSchema,
        into lines: inout [String]
    ) {
        lines.append("private func \(fnName)(_ value: \(swiftType), into writer: inout BridgeJSONWriter) {")
        lines.append("    writer.beginObject()")
        for (idx, field) in fields.enumerated() {
            lines.append("    writer.key(\"\(field.name)\", isFirst: \(idx == 0))")
            lines.append("    \(swiftEncodeExpr("value.\(field.name)", type: field.type, schema: schema))")
        }
        lines.append("    writer.endObject()")
        lines.append("}")
    }

    private static func emitStructDecoder(
        fnName: String,
        swiftType: String,
        fields: [ValueField],
        schema: BridgeSchema,
        into lines: inout [String]
    ) {
        lines.append("private func \(fnName)(from json: BridgeJSONValue) throws -> \(swiftType) {")
        lines.append("    guard case .object(let map) = json else { throw BridgeJSONError.expectedObject(\"\(swiftType)\") }")
        for field in fields {
            let decodeExpr = swiftDecodeField(key: field.name, type: field.type, schema: schema)
            lines.append("    let \(field.name) = \(decodeExpr)")
        }
        let initArgs = fields.map { "\($0.name): \($0.name)" }.joined(separator: ", ")
        lines.append("    return \(swiftType)(\(initArgs))")
        lines.append("}")
    }

    private static func emitEnumEncoder(
        fnName: String,
        swiftType: String,
        spec: EnumSpec,
        schema: BridgeSchema,
        into lines: inout [String]
    ) {
        lines.append("private func \(fnName)(_ value: \(swiftType), into writer: inout BridgeJSONWriter) {")
        lines.append("    switch value {")
        if spec.isSimple {
            for c in spec.cases {
                lines.append("    case .\(c.name):")
                lines.append("        writer.writeString(\"\(c.name)\")")
            }
        } else {
            for c in spec.cases {
                if c.params.isEmpty {
                    lines.append("    case .\(c.name):")
                    lines.append("        writer.beginObject()")
                    lines.append("        writer.key(\"kind\", isFirst: true)")
                    lines.append("        writer.writeString(\"\(c.name)\")")
                    lines.append("        writer.endObject()")
                } else {
                    let bindings = c.params.map { "let \($0.name)" }.joined(separator: ", ")
                    lines.append("    case .\(c.name)(\(bindings)):")
                    lines.append("        writer.beginObject()")
                    lines.append("        writer.key(\"kind\", isFirst: true)")
                    lines.append("        writer.writeString(\"\(c.name)\")")
                    for p in c.params {
                        lines.append("        writer.key(\"\(p.name)\", isFirst: false)")
                        lines.append("        \(swiftEncodeExpr(p.name, type: p.type, schema: schema))")
                    }
                    lines.append("        writer.endObject()")
                }
            }
        }
        lines.append("    }")
        lines.append("}")
    }

    private static func emitEnumDecoder(
        fnName: String,
        swiftType: String,
        spec: EnumSpec,
        schema: BridgeSchema,
        forceTaggedObject: Bool = false,
        into lines: inout [String]
    ) {
        lines.append("private func \(fnName)(from json: BridgeJSONValue) throws -> \(swiftType) {")
        if spec.isSimple && !forceTaggedObject {
            lines.append("    guard case .string(let raw) = json else { throw BridgeJSONError.expectedString(\"\(swiftType)\") }")
            lines.append("    switch raw {")
            for c in spec.cases {
                lines.append("    case \"\(c.name)\": return .\(c.name)")
            }
            lines.append("    default: throw BridgeJSONError.unknownCase(raw)")
            lines.append("    }")
        } else {
            lines.append("    guard case .object(let map) = json, case .string(let kind)? = map[\"kind\"] else {")
            lines.append("        throw BridgeJSONError.expectedObject(\"\(swiftType)\")")
            lines.append("    }")
            lines.append("    switch kind {")
            for c in spec.cases {
                if c.params.isEmpty {
                    lines.append("    case \"\(c.name)\": return .\(c.name)")
                } else {
                    lines.append("    case \"\(c.name)\":")
                    for p in c.params {
                        lines.append("        let \(p.name) = \(swiftDecodeField(key: p.name, type: p.type, schema: schema))")
                    }
                    let args = c.params.map { p -> String in
                        if let label = p.label {
                            return "\(label): \(p.name)"
                        }
                        return p.name
                    }.joined(separator: ", ")
                    lines.append("        return .\(c.name)(\(args))")
                }
            }
            lines.append("    default: throw BridgeJSONError.unknownCase(kind)")
            lines.append("    }")
        }
        lines.append("}")
    }

    private static func swiftEncodeExpr(_ expr: String, type: BridgeType, schema: BridgeSchema, writer: String = "writer") -> String {
        switch type {
        case .primitive(.bool): return "\(writer).writeBool(\(expr))"
        case .primitive(.int): return "\(writer).writeInt(\(expr))"
        case .primitive(.int64): return "\(writer).writeInt64(\(expr))"
        case .primitive(.double): return "\(writer).writeDouble(\(expr))"
        case .primitive(.string): return "\(writer).writeString(\(expr))"
        case .optional(let inner):
            return "if let v = \(expr) { \(swiftEncodeExpr("v", type: inner, schema: schema, writer: writer)) } else { \(writer).writeNull() }"
        case .array(let inner):
            return "\(writer).writeArray(\(expr)) { item, w in \(swiftEncodeExpr("item", type: inner, schema: schema, writer: "w")) }"
        case .named(let fullName):
            return "encode\(swiftFuncSuffix(for: fullName))(\(expr), into: &\(writer))"
        }
    }

    private static func swiftDecodeField(key: String, type: BridgeType, schema: BridgeSchema) -> String {
        switch type {
        case .optional(let inner):
            let innerDecode = swiftDecodeValue("raw", type: inner, schema: schema)
            return "try { () -> \(swiftTypeName(type)) in guard let raw = map[\"\(key)\"], raw != .null else { return nil }; return \(innerDecode) }()"
        default:
            let innerDecode = swiftDecodeValue("raw", type: type, schema: schema)
            return "try { () -> \(swiftTypeName(type)) in guard let raw = map[\"\(key)\"] else { throw BridgeJSONError.missingField(\"\(key)\") }; return \(innerDecode) }()"
        }
    }

    private static func swiftDecodeValue(_ varName: String, type: BridgeType, schema: BridgeSchema) -> String {
        switch type {
        case .primitive(.bool): return "try \(varName).asBool()"
        case .primitive(.int): return "try \(varName).asInt()"
        case .primitive(.int64): return "try \(varName).asInt64()"
        case .primitive(.double): return "try \(varName).asDouble()"
        case .primitive(.string): return "try \(varName).asString()"
        case .optional(let inner):
            return "\(varName) == .null ? nil : \(swiftDecodeValue(varName, type: inner, schema: schema))"
        case .array(let inner):
            return "try \(varName).asArray().map { item in \(swiftDecodeValue("item", type: inner, schema: schema)) }"
        case .named(let fullName):
            return "try decode\(swiftFuncSuffix(for: fullName))(from: \(varName))"
        }
    }

    private static func swiftTypeName(_ type: BridgeType) -> String {
        switch type {
        case .primitive(let p): return p.rawValue
        case .optional(let inner): return "\(swiftTypeName(inner))?"
        case .array(let inner): return "[\(swiftTypeName(inner))]"
        case .named(let fullName): return fullName
        }
    }

    private static func swiftFuncSuffix(for fullName: String) -> String {
        fullName.split(separator: ".").map(String.init).joined()
    }
}

private let runtimeJSONHelpers = #"""
enum BridgeJSONError: Error {
    case invalidJSON
    case expectedObject(String)
    case expectedString(String)
    case expectedNumber(String)
    case expectedBool(String)
    case expectedArray(String)
    case missingField(String)
    case unknownCase(String)
}

private struct BridgeJSONWriter {
    var result: String = ""

    mutating func beginObject() { result.append("{") }
    mutating func endObject() { result.append("}") }

    mutating func key(_ name: String, isFirst: Bool) {
        if !isFirst { result.append(",") }
        writeString(name)
        result.append(":")
    }

    mutating func writeNull() { result.append("null") }
    mutating func writeBool(_ v: Bool) { result.append(v ? "true" : "false") }
    mutating func writeInt(_ v: Int) { result.append(String(v)) }
    mutating func writeInt64(_ v: Int64) { result.append(String(v)) }
    mutating func writeDouble(_ v: Double) { result.append(String(v)) }

    mutating func writeString(_ s: String) {
        result.append("\"")
        for scalar in s.unicodeScalars {
            switch scalar.value {
            case 0x22: result.append("\\\"")
            case 0x5C: result.append("\\\\")
            case 0x08: result.append("\\b")
            case 0x0C: result.append("\\f")
            case 0x0A: result.append("\\n")
            case 0x0D: result.append("\\r")
            case 0x09: result.append("\\t")
            case 0x00..<0x20:
                let hex = String(scalar.value, radix: 16)
                result.append("\\u" + String(repeating: "0", count: 4 - hex.count) + hex)
            default:
                result.unicodeScalars.append(scalar)
            }
        }
        result.append("\"")
    }

    mutating func writeArray<T>(_ items: [T], writeItem: (T, inout BridgeJSONWriter) -> Void) {
        result.append("[")
        for (i, item) in items.enumerated() {
            if i > 0 { result.append(",") }
            writeItem(item, &self)
        }
        result.append("]")
    }
}

private enum BridgeJSONValue: Equatable {
    case null
    case bool(Bool)
    case number(String)
    case string(String)
    case array([BridgeJSONValue])
    case object([String: BridgeJSONValue])

    func asBool() throws -> Bool {
        guard case .bool(let v) = self else { throw BridgeJSONError.expectedBool("Bool") }
        return v
    }

    func asInt() throws -> Int {
        guard case .number(let raw) = self, let v = Int(raw) else { throw BridgeJSONError.expectedNumber("Int") }
        return v
    }

    func asInt64() throws -> Int64 {
        guard case .number(let raw) = self, let v = Int64(raw) else { throw BridgeJSONError.expectedNumber("Int64") }
        return v
    }

    func asDouble() throws -> Double {
        guard case .number(let raw) = self, let v = Double(raw) else { throw BridgeJSONError.expectedNumber("Double") }
        return v
    }

    func asString() throws -> String {
        guard case .string(let v) = self else { throw BridgeJSONError.expectedString("String") }
        return v
    }

    func asArray() throws -> [BridgeJSONValue] {
        guard case .array(let v) = self else { throw BridgeJSONError.expectedArray("Array") }
        return v
    }
}

private struct BridgeJSONParser {
    private let bytes: [UInt8]
    private var idx: Int = 0

    static func parse(_ text: String) throws -> BridgeJSONValue {
        var parser = BridgeJSONParser(bytes: Array(text.utf8))
        let val = try parser.parseValue()
        parser.skipWhitespace()
        guard parser.idx == parser.bytes.count else { throw BridgeJSONError.invalidJSON }
        return val
    }

    private mutating func skipWhitespace() {
        while idx < bytes.count {
            switch bytes[idx] {
            case 0x20, 0x09, 0x0A, 0x0D: idx += 1
            default: return
            }
        }
    }

    private mutating func parseValue() throws -> BridgeJSONValue {
        skipWhitespace()
        guard idx < bytes.count else { throw BridgeJSONError.invalidJSON }
        switch bytes[idx] {
        case 0x7B: return try parseObject()
        case 0x5B: return try parseArray()
        case 0x22: return .string(try parseString())
        case 0x74:
            guard matchLiteral("true") else { throw BridgeJSONError.invalidJSON }
            return .bool(true)
        case 0x66:
            guard matchLiteral("false") else { throw BridgeJSONError.invalidJSON }
            return .bool(false)
        case 0x6E:
            guard matchLiteral("null") else { throw BridgeJSONError.invalidJSON }
            return .null
        default:
            return try parseNumber()
        }
    }

    private mutating func matchLiteral(_ lit: String) -> Bool {
        let utf8 = Array(lit.utf8)
        guard idx + utf8.count <= bytes.count else { return false }
        for i in 0..<utf8.count where bytes[idx + i] != utf8[i] { return false }
        idx += utf8.count
        return true
    }

    private mutating func parseObject() throws -> BridgeJSONValue {
        idx += 1
        var map: [String: BridgeJSONValue] = [:]
        skipWhitespace()
        if idx < bytes.count, bytes[idx] == 0x7D { idx += 1; return .object(map) }
        while true {
            skipWhitespace()
            let key = try parseString()
            skipWhitespace()
            guard idx < bytes.count, bytes[idx] == 0x3A else { throw BridgeJSONError.invalidJSON }
            idx += 1
            map[key] = try parseValue()
            skipWhitespace()
            guard idx < bytes.count else { throw BridgeJSONError.invalidJSON }
            if bytes[idx] == 0x7D { idx += 1; return .object(map) }
            guard bytes[idx] == 0x2C else { throw BridgeJSONError.invalidJSON }
            idx += 1
        }
    }

    private mutating func parseArray() throws -> BridgeJSONValue {
        idx += 1
        var items: [BridgeJSONValue] = []
        skipWhitespace()
        if idx < bytes.count, bytes[idx] == 0x5D { idx += 1; return .array(items) }
        while true {
            items.append(try parseValue())
            skipWhitespace()
            guard idx < bytes.count else { throw BridgeJSONError.invalidJSON }
            if bytes[idx] == 0x5D { idx += 1; return .array(items) }
            guard bytes[idx] == 0x2C else { throw BridgeJSONError.invalidJSON }
            idx += 1
        }
    }

    private mutating func parseString() throws -> String {
        guard idx < bytes.count, bytes[idx] == 0x22 else { throw BridgeJSONError.invalidJSON }
        idx += 1
        var out: [UInt8] = []
        while idx < bytes.count {
            let b = bytes[idx]
            idx += 1
            if b == 0x22 {
                guard let s = String(bytes: out, encoding: .utf8) else { throw BridgeJSONError.invalidJSON }
                return s
            }
            if b == 0x5C {
                guard idx < bytes.count else { throw BridgeJSONError.invalidJSON }
                let esc = bytes[idx]
                idx += 1
                switch esc {
                case 0x22: out.append(0x22)
                case 0x5C: out.append(0x5C)
                case 0x2F: out.append(0x2F)
                case 0x62: out.append(0x08)
                case 0x66: out.append(0x0C)
                case 0x6E: out.append(0x0A)
                case 0x72: out.append(0x0D)
                case 0x74: out.append(0x09)
                case 0x75:
                    guard idx + 4 <= bytes.count,
                          let hex = String(bytes: bytes[idx..<(idx + 4)], encoding: .utf8),
                          let code = UInt32(hex, radix: 16),
                          let scalar = UnicodeScalar(code) else {
                        throw BridgeJSONError.invalidJSON
                    }
                    idx += 4
                    out.append(contentsOf: String(scalar).utf8)
                default: throw BridgeJSONError.invalidJSON
                }
            } else {
                out.append(b)
            }
        }
        throw BridgeJSONError.invalidJSON
    }

    private mutating func parseNumber() throws -> BridgeJSONValue {
        let start = idx
        while idx < bytes.count {
            let b = bytes[idx]
            let isNum = (b >= 0x30 && b <= 0x39) || b == 0x2D || b == 0x2B || b == 0x2E || b == 0x65 || b == 0x45
            if !isNum { break }
            idx += 1
        }
        guard idx > start, let raw = String(bytes: bytes[start..<idx], encoding: .utf8) else {
            throw BridgeJSONError.invalidJSON
        }
        return .number(raw)
    }
}
